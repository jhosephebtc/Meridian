function setHtml(sel: string, html: string): void {
  const el = document.querySelector(sel);
  if (el) el.innerHTML = html;
}

export function applyHomeI18n(lang: Lang): void {
  const dict = HOME[lang] ?? HOME.pt;
  setHtml('#home-historia-prose', ESSAY[lang] ?? ESSAY.pt);
  document.querySelectorAll<HTMLElement>('[data-home]').forEach((el) => {
    const key = el.getAttribute('data-home');
    if (!key) return;
    const val = dict[`home.${key}`];
    if (val == null) return;
    if (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement) {
      el.placeholder = val;
      return;
    }
    el.textContent = val;
    if (el.hasAttribute('data-b2c')) el.dataset.b2c = val.replace(/&/g, '&amp;');
  });
  document.querySelectorAll<HTMLElement>('[data-home-html]').forEach((el) => {
    const key = el.getAttribute('data-home-html');
    if (!key) return;
    const val = dict[`home.${key}`];
    if (val == null) return;
    el.innerHTML = val;
    if (el.hasAttribute('data-b2c')) el.dataset.b2c = val;
  });
}
