export function applyPreviewI18n(lang: Lang): void {
  const dict = PREV[lang] ?? PREV.pt;
  document.querySelectorAll<HTMLElement>('[data-prev]').forEach((el) => {
    const key = el.getAttribute('data-prev');
    if (!key) return;
    const val = dict[key];
    if (val == null) return;
    if (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement) {
      el.placeholder = val;
      return;
    }
    el.textContent = val;
  });
  document.querySelectorAll<HTMLElement>('[data-prev-html]').forEach((el) => {
    const key = el.getAttribute('data-prev-html');
    if (!key) return;
    const val = dict[key];
    if (val == null) return;
    el.innerHTML = val;
  });
}
